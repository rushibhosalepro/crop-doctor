// Minimal offline shell for Crop Doctor.
// - Page loads: network first, so a new deploy shows at once; the cached
//   copy is used only when there is no connection.
// - Same-origin files (hashed JS/CSS, sample and eval photos): cache first.
// - Other origins (Firebase AI Logic, App Check, reCAPTCHA) are never cached.
const CACHE = "cropdoctor-shell-v1";
const SHELL = [
  "/",
  "/index.html",
  "/samples/sample_spotted.jpg",
  "/samples/sample_healthy.jpg",
  "/samples/sample_newshoots.jpg",
  "/samples/sample_notplant.jpg",
];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === "navigate") {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put("/index.html", copy));
          return res;
        })
        .catch(() => caches.match("/index.html"))
    );
    return;
  }

  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
    )
  );
});
