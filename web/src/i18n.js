export const STR = { en: EN, mr: MR, hi: HI };

const valid = (l) => (STR[l] ? l : "en");

/** Translate a key, falling back to English, then the key itself. */
export function tx(lang, key) {
  const d = STR[valid(lang)] || EN;
  return d[key] ?? EN[key] ?? key;
}

/** Persisted UI language. Also sets <html lang> for screen readers. */
export function useLang() {
  const [lang, setLang] = useState(() => {
    try {
      return valid(localStorage.getItem("crop-doctor-lang") || "en");
    } catch {
      return "en";
    }
  });
  useEffect(() => {
    try {
      localStorage.setItem("crop-doctor-lang", lang);
    } catch {
      /* private mode: keep in memory */
    }
    document.documentElement.lang = LOCALES[lang] || "en-IN";
  }, [lang]);
  return [lang, setLang];
}

/**
 * Display name for a crop token (chip value) or the model's English guess,
 * in the UI language. Falls back to the raw text for English.
 */
export function cropDisplay(raw, lang) {
  if (!raw || !String(raw).trim()) return "";
  if (valid(lang) === "en") {
    const s = String(raw).trim();
    return s.charAt(0).toUpperCase() + s.slice(1);
  }
  const key = String(raw).trim().toLowerCase();
  const crops = STR[valid(lang)].crops;
  if (crops[key]) return crops[key];
  // Model guess in English ("Sapota", "maize plant"): match known names.
  const enNames = STR.en.crops;
  for (const [k, name] of Object.entries(enNames)) {
    if (key === name.toLowerCase() || key.includes(name.toLowerCase()) || name.toLowerCase().includes(key)) {
      return crops[k] || name;
    }
  }
  return String(raw).trim();
}
